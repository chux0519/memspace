// Package pi integrates pi (pi-coding-agent) with MemSpace.
//
// pi has no shell hooks: it loads TypeScript extensions from
// <agent dir>/extensions/*.ts and MCP servers from <agent dir>/mcp.json.
// `memspace agent install pi` therefore generates a small extension that
// forwards pi's lifecycle, prompt and tool events to `memspace hook pi` (the
// same payload shape Claude Code sends) and registers the stdio MCP bridge
// next to it.
package pi

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/chux0519/memspace/internal/adapter"
	"github.com/chux0519/memspace/internal/adapter/hookpayload"
	"github.com/chux0519/memspace/internal/spool"
)

const agentName = "pi"

// AgentType is the agent_type stored on sessions.
const AgentType = "pi"

// extensionMarker identifies the extension file MemSpace owns; Uninstall only
// deletes a file that carries it.
const extensionMarker = "Generated by memspace (memspace agent install pi)"

// Adapter implements adapter.Adapter for pi.
type Adapter struct {
	// AgentDir overrides pi's agent directory (default $PI_CODING_AGENT_DIR
	// or ~/.pi/agent).
	AgentDir string
}

func (a *Adapter) Name() string { return agentName }

func (a *Adapter) agentDir() string {
	if a.AgentDir != "" {
		return a.AgentDir
	}
	if v := os.Getenv("PI_CODING_AGENT_DIR"); v != "" {
		return v
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".pi", "agent")
}

// ExtensionPath is the extension file that forwards pi's events to MemSpace.
func (a *Adapter) ExtensionPath() string {
	return filepath.Join(a.agentDir(), "extensions", "memspace.ts")
}

// MCPConfigPath is pi's user-level MCP config file.
func (a *Adapter) MCPConfigPath() string { return filepath.Join(a.agentDir(), "mcp.json") }

func (a *Adapter) Capabilities() []string {
	return []string{"session.started", "user.prompt", "tool.completed", "tool.failed",
		"file.modified", "agent.turn_completed", "session.compacting", "session.ended"}
}

func (a *Adapter) Detect(ctx context.Context) adapter.Detection {
	d := adapter.Detection{ConfigDir: a.agentDir()}
	if p, err := exec.LookPath("pi"); err == nil {
		d.Found = true
		d.Binary = p
		ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
		defer cancel()
		if out, err := exec.CommandContext(ctx, p, "--version").Output(); err == nil {
			d.Version = strings.TrimSpace(string(out))
		}
	} else if _, err := os.Stat(d.ConfigDir); err == nil {
		d.Found = true
	}
	return d
}

// Install writes the capture extension. The MCP server is registered
// separately through RegisterMCP so `--no-mcp` still leaves capture working.
func (a *Adapter) Install(ctx context.Context, opts adapter.InstallOptions) error {
	if len(opts.HookArgv) == 0 {
		return errors.New("pi: hook argv is required to generate the extension")
	}
	path := a.ExtensionPath()
	existing, err := os.ReadFile(path)
	switch {
	case err == nil && !strings.Contains(string(existing), extensionMarker):
		return fmt.Errorf("%s already exists and was not generated by memspace; move it aside first", path)
	case err != nil && !errors.Is(err, os.ErrNotExist):
		return err
	}
	src, err := ExtensionSource(opts.HookArgv)
	if err != nil {
		return err
	}
	// Reinstalling rewrites the same content with this binary's command; the
	// file is only touched when it changed, so a re-run stays idempotent.
	if string(existing) != string(src) {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			return err
		}
	}
	fmt.Fprintf(opts.Out, "Installed pi extension in %s\n", path)
	fmt.Fprintf(opts.Out, "  events:  %s\n", strings.Join([]string{
		"session_start", "session_shutdown", "input", "before_agent_start", "tool_result",
		"agent_settled", "session_before_compact",
	}, ", "))
	fmt.Fprintf(opts.Out, "  command: %s\n", opts.HookCommand)
	fmt.Fprintln(opts.Out, "New pi sessions will be captured; /reload or restart running ones.")
	return nil
}

func (a *Adapter) Uninstall(ctx context.Context, out io.Writer) error {
	path := a.ExtensionPath()
	data, err := os.ReadFile(path)
	switch {
	case errors.Is(err, os.ErrNotExist):
		fmt.Fprintf(out, "No MemSpace extension found in %s\n", path)
		return nil
	case err != nil:
		return err
	case !strings.Contains(string(data), extensionMarker):
		fmt.Fprintf(out, "%s was not generated by memspace; leaving it in place\n", path)
		return nil
	}
	if err := os.Remove(path); err != nil {
		return err
	}
	fmt.Fprintf(out, "Removed MemSpace extension %s\n", path)
	return nil
}

func (a *Adapter) Doctor(ctx context.Context, opts adapter.InstallOptions) []adapter.Check {
	var checks []adapter.Check
	d := a.Detect(ctx)
	switch {
	case d.Binary != "":
		checks = append(checks, adapter.Check{Name: "pi binary", Status: adapter.OK, Detail: d.Binary + " " + d.Version})
	case d.Found:
		checks = append(checks, adapter.Check{Name: "pi binary", Status: adapter.Warn, Detail: "not on PATH, but " + d.ConfigDir + " exists"})
	default:
		checks = append(checks, adapter.Check{Name: "pi binary", Status: adapter.Fail, Detail: "pi not found"})
	}

	checks = append(checks, a.extensionCheck(opts))
	checks = append(checks, adapter.SelfTest(ctx, agentName, opts.HookCommand, sampleToolResult()))
	return checks
}

// extensionCheck verifies the generated extension exists and runs this
// binary's hook command.
func (a *Adapter) extensionCheck(opts adapter.InstallOptions) adapter.Check {
	name := "hooks"
	path := a.ExtensionPath()
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return adapter.Check{Name: name, Status: adapter.Fail, Detail: "not installed (run 'memspace agent install pi')"}
	}
	if err != nil {
		return adapter.Check{Name: name, Status: adapter.Fail, Detail: err.Error()}
	}
	src := string(data)
	if !strings.Contains(src, extensionMarker) {
		return adapter.Check{Name: name, Status: adapter.Fail, Detail: path + " was not generated by memspace"}
	}
	if len(opts.HookArgv) > 0 {
		want, _ := json.Marshal(opts.HookArgv)
		if !strings.Contains(src, string(want)) {
			return adapter.Check{Name: name, Status: adapter.Warn,
				Detail: "installed command differs from this binary's (re-run 'memspace agent install pi')"}
		}
	}
	return adapter.Check{Name: name, Status: adapter.OK, Detail: path}
}

func sampleToolResult() []byte {
	b, _ := json.Marshal(map[string]any{
		"session_id":      "memspace-doctor",
		"cwd":             os.TempDir(),
		"hook_event_name": "PostToolUse",
		"tool_name":       "bash",
		"tool_use_id":     "call_doctor",
		"tool_input":      map[string]any{"command": "echo ok"},
		"tool_response":   map[string]any{"output": "ok"},
	})
	return b
}

// Normalize accepts the same payload shape the generated extension sends. pi
// reports the files a multi-file tool applied in the tool result, so the
// normalizer trusts such a result for any tool: pi has no dispatch layer that
// could hide a nested result, and its read-only tools never name files. pi's
// file tools take relative paths, which are completed with the session cwd so
// changed files match across devices.
func (a *Adapter) Normalize(raw []byte, now time.Time) ([]spool.Record, error) {
	return hookpayload.NormalizeWith(AgentType, raw, now, nil, hookpayload.Rules{
		ResultFilesAnyTool: true,
		ResolveInputPaths:  true,
	})
}
